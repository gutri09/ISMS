export const getCountriesByContinent = (
  continent?: string | string[],
  customList?: Country[]
): Country[] => {
  const pool = customList && Array.isArray(customList) && customList.length > 0 ? customList : COUNTRIES;
  if (!continent) return pool;
  if (Array.isArray(continent)) {
    const active = continent.filter((b) => b && b !== 'Semua');
    if (active.length === 0) return pool;
    const lower = active.map((b) => b.toLowerCase());
    return pool.filter((c) => lower.includes((c?.continent || '').toLowerCase()));
  }
  if (continent === 'Semua') return pool;
  return pool.filter((c) => (c?.continent || '').toLowerCase() === continent.toLowerCase());
};

export const normalizeCountryName = (input: string, customList?: Country[]): Country | undefined => {
  if (!input || !input.trim()) return undefined;
  const pool = customList && customList.length > 0 ? customList : COUNTRIES;
  const clean = input.trim().toLowerCase();
  
  // 1. Direct name or code match in pool
  const directInPool = pool.find(
    (c) => c.name.toLowerCase() === clean || c.code.toLowerCase() === clean
  );
  if (directInPool) return directInPool;

  // 2. Direct name or code match in base COUNTRIES
  const directInBase = COUNTRIES.find(
    (c) => c.name.toLowerCase() === clean || c.code.toLowerCase() === clean
  );
  if (directInBase) return directInBase;

  // 3. Common aliases
  const aliasMap: Record<string, string> = {
    'usa': 'Amerika Serikat',
    'united states': 'Amerika Serikat',
    'us': 'Amerika Serikat',
    'u.s.': 'Amerika Serikat',
    'u.s.a.': 'Amerika Serikat',
    'uk': 'Inggris',
    'united kingdom': 'Inggris',
    'great britain': 'Inggris',
    'britania raya': 'Inggris',
    'russia': 'Rusia',
    'germany': 'Jerman',
    'france': 'Prancis',
    'italy': 'Italia',
    'spain': 'Spanyol',
    'netherlands': 'Belanda',
    'holland': 'Belanda',
    'switzerland': 'Swiss',
    'brazil': 'Brasil',
    'czech republic': 'Ceko',
    'czechia': 'Ceko',
    'belarusia': 'Belarus',
    'turkey': 'Turki',
    'turki': 'Turki',
    'turkiye': 'Turki',
    'türkiye': 'Turki',
    'tr': 'Turki',
    'china': 'Tiongkok',
    'prc': 'Tiongkok',
    'tiongkok': 'Tiongkok',
    'japan': 'Jepang',
    'korea': 'Korea Selatan',
    'south korea': 'Korea Selatan',
    'australia': 'Australia',
    'indonesia': 'Indonesia',
  };

  const mapped = aliasMap[clean];
  if (mapped) {
    const foundMapped = pool.find((c) => c.name.toLowerCase() === mapped.toLowerCase())
      || COUNTRIES.find((c) => c.name.toLowerCase() === mapped.toLowerCase());
    if (foundMapped) return foundMapped;
    return {
      code: mapped.slice(0, 2).toUpperCase(),
      name: mapped,
      continent: 'Eropa',
    };
  }

  // 4. Partial / Includes match in pool
  const partial = pool.find(
    (c) => c.name.toLowerCase().includes(clean) || clean.includes(c.name.toLowerCase())
  );
  if (partial) return partial;

  // 5. Fallback: Dynamically accept custom country without throwing hard error
  if (clean.length >= 2) {
    return {
      code: clean.slice(0, 2).toUpperCase(),
      name: input.trim(),
      continent: 'Eropa',
    };
  }

  return undefined;
};
